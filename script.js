function setLanguage(language) {

    const dictionary = translations[language];

    if (!dictionary) {
        console.error("Unknown language:", language);
        return;
    }

    // Звичайний текст
    document.querySelectorAll("[data-i18n]").forEach(element => {

        const key = element.dataset.i18n;

        if (dictionary[key] !== undefined) {
            element.innerHTML = dictionary[key];
        }

    });


    // Meta description / OG description
    document.querySelectorAll("[data-i18n-content]").forEach(element => {

        const key = element.dataset.i18nContent;

        if (dictionary[key] !== undefined) {
            element.setAttribute(
                "content",
                dictionary[key]
            );
        }

    });


    // Title
    if (dictionary.metaTitle) {
        document.title = dictionary.metaTitle;
    }


    // HTML language
    document.documentElement.lang = language;


    // Зберігаємо вибір
    localStorage.setItem(
        "nomark-language",
        language
    );


    // Оновлюємо активну кнопку в шапці
    document
        .querySelectorAll(".language-button")
        .forEach(button => {

            button.classList.toggle(
                "active",
                button.dataset.language === language
            );

        });
}


/* =========================================
   LANGUAGE SYSTEM
========================================= */

document.addEventListener("DOMContentLoaded", () => {

    const modal = document.getElementById("languageModal");

    const modalOptions = document.querySelectorAll(
        ".language-option"
    );

    const headerButtons = document.querySelectorAll(
        ".language-button"
    );


    /* ================================
       CHANGE LANGUAGE
    ================================= */

    function changeLanguage(language) {

        const dictionary = translations[language];

        if (!dictionary) {
            console.error(
                "Language not found:",
                language
            );

            return;
        }


        /* TEXT */

        document
            .querySelectorAll("[data-i18n]")
            .forEach(element => {

                const key =
                    element.dataset.i18n;

                if (
                    dictionary[key] !== undefined
                ) {

                    element.innerHTML =
                        dictionary[key];

                }

            });


        /* META */

        document
            .querySelectorAll("[data-i18n-content]")
            .forEach(element => {

                const key =
                    element.dataset.i18nContent;

                if (
                    dictionary[key] !== undefined
                ) {

                    element.setAttribute(
                        "content",
                        dictionary[key]
                    );

                }

            });


        /* TITLE */

        if (dictionary.metaTitle) {

            document.title =
                dictionary.metaTitle;

        }


        /* HTML LANG */

        document.documentElement.lang =
            language;


        /* SAVE */

        localStorage.setItem(
            "nomark-language",
            language
        );


        /* HEADER BUTTONS */

        headerButtons.forEach(button => {

            button.classList.toggle(
                "active",
                button.dataset.language === language
            );

        });


        console.log(
            "NoMark language:",
            language
        );

    }


    /* ================================
       MODAL LANGUAGE BUTTONS
    ================================= */

    modalOptions.forEach(option => {

        option.addEventListener(
            "click",
            () => {

                const language =
                    option.dataset.language;


                console.log(
                    "Language selected:",
                    language
                );


                changeLanguage(language);


                if (modal) {

                    modal.classList.add(
                        "hidden"
                    );

                }

            }
        );

    });


    /* ================================
       HEADER LANGUAGE BUTTONS
    ================================= */

    headerButtons.forEach(button => {

        button.addEventListener(
            "click",
            () => {

                const language =
                    button.dataset.language;


                changeLanguage(language);

            }
        );

    });


    /* ================================
       DETECT LANGUAGE
    ================================= */

    const savedLanguage =
        localStorage.getItem(
            "nomark-language"
        );


    const browserLanguage =
        navigator.language.toLowerCase();


    let defaultLanguage = "en";


    if (
        browserLanguage.startsWith("uk")
    ) {

        defaultLanguage = "uk";

    } else if (
        browserLanguage.startsWith("ru")
    ) {

        defaultLanguage = "ru";

    }


    /* ================================
       INITIALIZATION
    ================================= */

    if (savedLanguage) {

        changeLanguage(
            savedLanguage
        );


        if (modal) {

            modal.classList.add(
                "hidden"
            );

        }

    } else {

        /*
         * Перший візит.
         *
         * Ставимо мову браузера,
         * але модалку залишаємо відкритою.
         */

        changeLanguage(
            defaultLanguage
        );

    }

});